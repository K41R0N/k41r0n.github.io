#!/usr/bin/env python3
"""Rewrite MANIFEST.md from packs/*/pack.yaml: name, version, status, sha256 over the pack's files."""
import glob, hashlib, os, re
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = []
for pk in sorted(glob.glob(os.path.join(root, "packs", "*"))):
    h = hashlib.sha256()
    for f in sorted(glob.glob(os.path.join(pk, "**", "*"), recursive=True)):
        if os.path.isfile(f):
            h.update(os.path.relpath(f, pk).encode()); h.update(open(f, "rb").read())
    y = open(os.path.join(pk, "pack.yaml")).read()
    g = lambda k: (re.search(rf"^{k}:\s*(\S+)", y, re.M) or [None, "?"])[1]
    rows.append(f"| {os.path.basename(pk)} | {g('version')} | {g('status')} | {h.hexdigest()[:12]} |")
open(os.path.join(root, "MANIFEST.md"), "w").write("# Manifest\n\nGenerated by scripts/manifest.py. Do not edit by hand.\n\n| Pack | Version | Status | Hash |\n|---|---|---|---|\n" + "\n".join(rows) + "\n")
