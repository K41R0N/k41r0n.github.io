#!/usr/bin/env python3
"""Join the Wikipedia watch-list candidates with his actual corpus.

Reads knowledge/voice/refs/wiki-ai-signs-candidates.txt (generated by
wiki_signs_update.py) and assets/voice-corpus/raw/*.md, and writes
knowledge/voice/refs/wiki-ai-signs-evidence.json: for every candidate entry,
its checkable word/phrase forms and how often he actually uses each.

The governing rule is ban_list.py's: a word is banned only if he never uses it
in corpus/raw. So the evidence classes are:
  zero_use   - every checkable form is absent from his corpus: ban-ELIGIBLE,
               still unconfirmed (his call, lexicon.md open question)
  used       - he uses at least one form: not bannable, whatever the source says
  uncheckable - the entry is an open-ended pattern (ellipsis/placeholder), no
               deterministic form; a human reads it in context

checks.py rule W08 flags only zero_use entries, so the writing path never
implies every Wikipedia word is banned and never flags a word he actually uses.

Usage: wiki_candidate_evidence.py [--self-test]
Stdlib only. Deterministic given the same candidates file and corpus.
"""
import glob
import hashlib
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))  # agent/
CANDIDATES = os.path.join(ROOT, 'knowledge', 'voice', 'refs', 'wiki-ai-signs-candidates.txt')
EVIDENCE = os.path.join(ROOT, 'knowledge', 'voice', 'refs', 'wiki-ai-signs-evidence.json')
CORPUS = os.path.join(ROOT, 'assets', 'voice-corpus', 'raw')


def corpus_files(corpus_dir):
    """Only top-level *.md in the raw corpus directory: the owner-authored essays
    the voice canon builds its spec from. excluded/ (authorship unverified) and
    holdout/ are separate directories and are never read here."""
    return sorted(glob.glob(os.path.join(corpus_dir, '*.md')))


def sha_of(paths):
    h = hashlib.sha256()
    for p in paths:
        h.update(os.path.basename(p).encode() + b'\0' + open(p, 'rb').read() + b'\0')
    return h.hexdigest()


def corpus_text(corpus_dir):
    parts = []
    for p in corpus_files(corpus_dir):
        parts.append(open(p, encoding='utf-8').read().lower())
    return ' '.join(parts)


def parse_candidates(path):
    """Yield (term, section) from the vocabulary section of the candidates file."""
    in_vocab = False
    for line in open(path, encoding='utf-8'):
        if line.startswith('## '):
            in_vocab = line.strip().startswith('## Vocabulary candidates')
            continue
        if in_vocab and line.startswith('- '):
            m = re.match(r'^- (.+?)  \[(.+)\]\s*$', line)
            if m:
                yield m.group(1), m.group(2)


def forms_of(term):
    """Split an entry into checkable forms. Returns (kind, forms).

    kind: 'word' (single-word slash alternatives), 'phrase' (literal multi-word
    alternatives), or 'uncheckable' (open-ended pattern)."""
    t = re.sub(r'\([^)]*\)', ' ', term)      # qualifiers
    t = re.sub(r'\[[^]]*\]', ' ', t)          # placeholders like [a], [source]
    if '...' in t or '…' in t:
        return 'uncheckable', []
    alts = []
    for a in t.split('/'):
        a = re.sub(r'\s+', ' ', a).strip(" ,;'\"")
        if a:
            alts.append(a)
    if not alts:
        return 'uncheckable', []
    if all(re.fullmatch(r"[A-Za-z][A-Za-z'-]*", a) for a in alts):
        return 'word', alts
    if len(alts) == 1:
        return 'phrase', alts
    # Slash groups spanning word boundaries ("a crucial/pivotal role/moment")
    # split into fragment alts that are not checkable units: record only.
    return 'uncheckable', []


def count_form(form, corpus):
    if re.fullmatch(r"[A-Za-z][A-Za-z'-]*", form):
        return len(re.findall(r'\b' + re.escape(form.lower()) + r'\b', corpus))
    return corpus.count(form.lower())


def build(candidates_path, corpus_dir):
    corpus = corpus_text(corpus_dir)
    corpus_words = len(re.findall(r"[a-z0-9']+", corpus))
    oldid = ''
    for line in open(candidates_path, encoding='utf-8'):
        m = re.search(r'oldid (\d+), revision (\S+)', line)
        if m:
            oldid, revts = m.group(1), m.group(2)
            break
    entries = []
    for term, section in parse_candidates(candidates_path):
        kind, forms = forms_of(term)
        hits = {f: count_form(f, corpus) for f in forms}
        # Per-form classes: the corpus rule is per word (ban_list.py BAN/KEEP lines),
        # so a slash-group entry does not shield an individually unused form.
        # auto_flag: lone words inside phrase-pattern entries (e.g. "moment" in
        # "key role/moment") stay evidence-only - a 15k-word corpus is weak
        # evidence for common words, so those need his confirmation, not a flag.
        form_class = {f: ('zero_use' if n == 0 else 'used') for f, n in hits.items()}
        auto = {f: (kind == 'word' or ' ' in f) for f in forms}
        vals = set(form_class.values())
        cls = 'uncheckable' if kind == 'uncheckable' else (
            'zero_use' if vals == {'zero_use'} else ('used' if vals == {'used'} else 'mixed'))
        entries.append({'term': term, 'section': section, 'kind': kind,
                        'forms': forms, 'corpus_hits': hits, 'form_class': form_class,
                        'auto_flag': auto, 'class': cls})
    import datetime as dt
    return {
        'schema': 'wiki-ai-signs-evidence/v1',
        'source': 'Wikipedia:Signs of AI writing',
        'source_oldid': oldid,
        'source_revision': revts if oldid else '',
        'generated_at': dt.datetime.now(dt.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'),
        'corpus_dir': os.path.relpath(corpus_dir, ROOT),
        'corpus_files': [os.path.basename(x) for x in corpus_files(corpus_dir)],
        'corpus_sha256': sha_of(corpus_files(corpus_dir)),
        'candidates_sha256': sha_of([candidates_path]),
        'corpus_scope': 'verified owner-authored raw essays only; excluded/ (authorship unverified) and holdout/ are never read. Zero use in a small corpus is weak evidence and never proof of AI writing; it supports personal calibration only and does not override channel or client constraints.',
        'corpus_words': corpus_words,
        'rule': 'a word is banned only if he never uses it in corpus/raw; zero_use = ban-eligible candidate, unconfirmed',
        'entries': entries,
    }


def zero_use_checks(evidence):
    """The forms checks.py W08 may flag: (kind, form) for zero_use entries only."""
    out = []
    for e in evidence['entries']:
        if e['kind'] == 'uncheckable':
            continue
        out.extend((e['kind'], f) for f, c in e.get('form_class', {}).items()
                   if c == 'zero_use' and e.get('auto_flag', {}).get(f, False))
    return out


def main(argv):
    if '--self-test' in argv:
        ev = build(CANDIDATES, CORPUS)
        assert ev['corpus_words'] > 1000, 'corpus not read'
        classes = {e['class'] for e in ev['entries']}
        assert 'zero_use' in classes and 'used' in classes, f'expected both classes, got {classes}'
        assert any(e['class'] == 'mixed' for e in ev['entries']), 'expected at least one mixed slash-group'
        used = [e['term'] for e in ev['entries'] if e['class'] == 'used']
        zero = [e['term'] for e in ev['entries'] if e['class'] == 'zero_use']
        print(f"self-test OK: {len(ev['entries'])} entries, corpus {ev['corpus_words']} words; "
              f"{len(zero)} zero-use, {len(used)} used, {sum(1 for e in ev['entries'] if e['class']=='uncheckable')} uncheckable")
        print('sample used (never flagged):', '; '.join(used[:5]))
        print('sample zero-use (W08 flags):', '; '.join(zero[:5]))
        return 0
    evidence = build(CANDIDATES, CORPUS)
    tmp = EVIDENCE + '.tmp'
    json.dump(evidence, open(tmp, 'w'), indent=1, ensure_ascii=False)
    os.replace(tmp, EVIDENCE)
    n = {c: sum(1 for e in evidence['entries'] if e['class'] == c) for c in ('zero_use', 'used', 'mixed', 'uncheckable')}
    forms_flagged = len(zero_use_checks(evidence))
    print(f"wrote {os.path.relpath(EVIDENCE, ROOT)}: entries {n['zero_use']} zero-use / {n['used']} used / {n['mixed']} mixed / "
          f"{n['uncheckable']} uncheckable; {forms_flagged} individual zero-use forms flagged "
          f"(source oldid {evidence['source_oldid']}, corpus {evidence['corpus_words']} words)")
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
