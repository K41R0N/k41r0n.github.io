#!/usr/bin/env python3
"""Rewrite MANIFEST.md from packs/*/pack.yaml: name, version, status, sha256 over the pack's files.

--check verifies MANIFEST.md matches the current packs and exits 1 on drift; it never writes."""
import glob, hashlib, os, re, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def render():
    rows = []
    for pk in sorted(glob.glob(os.path.join(root, "packs", "*"))):
        if not os.path.isdir(pk): continue
        h = hashlib.sha256()
        for f in sorted(glob.glob(os.path.join(pk, "**", "*"), recursive=True)):
            if "__pycache__" in f.split(os.sep): continue
            if os.path.isfile(f):
                h.update(os.path.relpath(f, pk).encode()); h.update(open(f, "rb").read())
        y = open(os.path.join(pk, "pack.yaml")).read()
        g = lambda k: (re.search(rf"^{k}:\s*(\S+)", y, re.M) or [None, "?"])[1]
        rows.append(f"| {os.path.basename(pk)} | {g('version')} | {g('status')} | {h.hexdigest()[:12]} |")
    return "# Manifest\n\nGenerated by scripts/manifest.py. Do not edit by hand.\n\n| Pack | Version | Status | Hash |\n|---|---|---|---|\n" + "\n".join(rows) + "\n"


if __name__ == "__main__":
    path = os.path.join(root, "MANIFEST.md")
    new = render()
    if "--check" in sys.argv:
        old = open(path).read() if os.path.exists(path) else ""
        if old == new:
            print("PASS manifest - MANIFEST.md matches current packs")
            sys.exit(0)
        stale = sorted(set(l for l in new.splitlines() if l.startswith("| ")) ^ set(l for l in old.splitlines() if l.startswith("| ")))
        print("FAIL manifest - MANIFEST.md is stale; run scripts/manifest.py. Differing rows: " + "; ".join(x.split("|")[1].strip() for x in stale))
        sys.exit(1)
    open(path, "w").write(new)
